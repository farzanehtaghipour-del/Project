  /* برچسب فارسی برای هر کلید ثبت‌شده — علامت، حال‌وهوا، خون‌ریزی، انرژی، خواب */
  function anyLabel(k) {
    var l = symLabel(k);
    if (l !== k) return l;
    l = labelOf(MOODS, k) || labelOf(FLOW, k) || labelOf(ENERGY, k) || labelOf(SLEEP, k);
    return l || k;
  }
  /* فاز یک تاریخ: از میزبان می‌پرسیم؛ اگر نبود، قاعدهٔ مستند پروژه در پیش‌نمایش */
  function phaseOf(jdn) {
    if (S.adapter.phaseOf) {
      try { return S.adapter.phaseOf(jdn); }
      catch (e) {
        /* v16: در ادغام (با آداپتور واقعی) فالبکِ پیش‌نمایش اجرا نمی‌شود —
           خطا ثبت و مقدار خنثی برمی‌گردد تا فاز/توصیهٔ اشتباه داده نشود */
        if (S.opts.adapter) { console.error("[symjournal] phaseOf failed:", e); return null; }
      }
    }
    return demoPhase(jdn);
  }
  function cycleModel() {
    if (S.adapter.model) {
      try { return S.adapter.model(); }
      catch (e) {
        if (S.opts.adapter) {
          console.error("[symjournal] model failed:", e);
          return { cycleLen: 28, periodLen: 6, starts: [], cur: null, late: false };
        }
      }
    }
    return demoModel();
  }
  /* ---- فالبک فقط برای پیش‌نمایش (در ادغام استفاده نمی‌شود) ----
     همان قاعدهٔ مستند پروژه: طول چرخه = میانگین فاصله‌های ۱۵..۹۰ روز،
     وگرنه ۲۸؛ تخمک‌گذاری = طول چرخه − ۱۴؛ پنجره = ۵ روز قبل تا ۱ روز بعد. */
  function demoModel() {
    var st = S.adapter.starts().slice().sort(function (a, b) { return a.jdn - b.jdn; });
    var diffs = [];
    for (var i = 1; i < st.length; i++) diffs.push(st[i].jdn - st[i - 1].jdn);
    var used = diffs.slice(-6).filter(function (d) { return d >= 15 && d <= 90; });
    var len = used.length ? Math.round(used.reduce(function (a, b) { return a + b; }, 0) / used.length) : 28;
    var plen = st.length && st[st.length - 1].plen ? st[st.length - 1].plen : 6;
    var last = st.length ? st[st.length - 1] : null;
    return {
      cycleLen: len, periodLen: plen, starts: st.map(function (s) { return s.jdn; }),
      cur: last ? { s: last.jdn, e: last.jdn + len, plen: plen, ov: last.jdn + len - 15, wf: last.jdn + len - 15 - 5, wt: last.jdn + len - 15 + 1, pe: last.jdn + plen - 1 } : null, /* v16: پنجرهٔ مستند ۵/۱ */
      late: last ? todayJdn() > last.jdn + len : false
    };
  }
  function demoPhase(jdn) {
    var M = cycleModel();
    if (!M.cur && !M.starts.length) return null;
    var starts = M.starts || [];
    var prev = null, next = null;
    for (var i = 0; i < starts.length; i++) {
      if (starts[i] <= jdn) prev = starts[i]; else { next = starts[i]; break; }
    }
    if (prev === null) return null;
    var len = next ? (next - prev) : M.cycleLen;
    var plen = M.periodLen;
    var day = jdn - prev + 1;
    var ov = len - 14, wf = ov - 5, wt = ov + 1; /* v16: پنجرهٔ مستند ۵/۱ — ۲۸ روزه: روزهای ۹ تا ۱۵ */
    var per = day <= plen;
    var fert = day >= wf && day <= wt;
    var p = per ? "mens" : (fert ? "ovul" : (day < wf ? "foll" : "lut"));
    if (M.late && prev === starts[starts.length - 1] && jdn >= prev + M.cycleLen) {
      return { p: "lut", day: day, lateUnknown: true };
    }
    return { p: p, day: day, per: per, fert: fert, ov: day === ov };
  }
  function phaseName(P) {
    if (!P) return "";
    if (P.lateUnknown) return "نامعلوم";
    if (P.per) return PHASE_NAME.mens;
    if (P.ov) return "تخمک‌گذاری";
    return PHASE_NAME[P.p] || "";
  }
  function phaseClass(P) {
    if (!P) return "";
    if (P.per) return "m-mens";
    if (P.fert) return "m-fert";
    return P.p === "foll" ? "m-foll" : "m-lut";
  }

  /* ==========================================================================
     ۵) گزارش‌ها — همه از دادهٔ واقعی، با ذکر تعداد روزها و چرخه‌های استفاده‌شده
     ========================================================================== */
  function cycleBounds() {
    var M = cycleModel();
    var starts = (M.starts || []).slice().sort(function (a, b) { return a - b; });
    var out = [];
    for (var i = 0; i < starts.length; i++) {
      /* v16 مورد ۶: نبود M.cur یا e نامعتبر → فقط طول چرخه؛ هیچ NaN وارد فیلتر نمی‌شود */
      var e = i + 1 < starts.length ? starts[i + 1]
            : (M.cur && typeof M.cur.e === "number" && isFinite(M.cur.e) ? M.cur.e : starts[i] + (M.cycleLen || 28));
      /* v16 مورد ۱: e و len (طول نمایشی) دست‌نخورده؛ حد فیلترِ جدا: چرخهٔ جاری تا
         ثبتِ شروع واقعی بعدی ادامه دارد (بدون بزرگ‌شدن cycleLen با دیرکرد) */
      var cur = (i === starts.length - 1);
      out.push({ i: i + 1, s: starts[i], e: e, len: e - starts[i], current: cur,
                 lim: cur ? Math.max(e, todayJdn() + 1) : e });
    }
    return { cycles: out, M: M };
  }
  function cycleReport() {
    var cb = cycleBounds(), M = cb.M;
    var all = entries();
    var cur = cb.cycles.length ? cb.cycles[cb.cycles.length - 1] : null;
    /* v16: حد فیلتر lim — ثبت‌های روزهای دیرکرد (بعد از موعد پیش‌بینی‌شده) هم می‌آیند */
    var inCycle = cur ? all.filter(function (e) { return e.jdn >= cur.s && e.jdn < cur.lim; }) : [];
    /* v11: با حذف جدول «کدام روزهای چرخه»، شمارش علائم به‌تفکیک فاز هم دیگر لازم نیست */
    var freq = {}, sevBag = {};
    inCycle.forEach(function (e) {
      (e.r.symptoms || []).forEach(function (s) {
        freq[s] = (freq[s] || 0) + 1;
        sevBag[s] = sevBag[s] || {};
        var v = sevOf(e.r, s);
        if (v) sevBag[s][v] = (sevBag[s][v] || 0) + 1;
      });
    });
    var list = Object.keys(freq).map(function (s) {
      var bag = sevBag[s] || {};
      var best = "", bn = 0;
      Object.keys(bag).forEach(function (v) { if (bag[v] > bn || (bag[v] === bn && SEV_RANK[v] > SEV_RANK[best])) { best = v; bn = bag[v]; } });
      return { k: s, n: freq[s], sev: best, pct: inCycle.length ? Math.round((freq[s] / inCycle.length) * 100) : 0 };
    }).sort(function (a, b) { return b.n - a.n || SEV_RANK[b.sev] - SEV_RANK[a.sev]; });
    return {
      cyclesTotal: cb.cycles.length, cycle: cur, entriesAll: all, entriesCycle: inCycle,
      loggedDays: inCycle.length, cycleLen: cur ? cur.len : (M.cycleLen || 28),
      periodLen: M.periodLen || 6, list: list,
      top: list.slice(0, 2).map(function (x) { return x.k; })
    };
  }
  function pastReport(limit) {
    var cb = cycleBounds();
    var all = entries();
    /* v17: با limit (PAST_CMP_MAX) فقط آخرین چرخه‌ها وارد مقایسه می‌شوند؛
       بدون پارامتر دقیقاً مثل v16: همهٔ چرخه‌ها. فیلتر ثبت هر چرخه همان قبلی است:
       e.jdn >= c.s && e.jdn < c.lim */
    var cmp = (typeof limit === "number" && limit > 0) ? cb.cycles.slice(-limit) : cb.cycles;
    var byIdx = {};
    cmp.forEach(function (c) { byIdx[c.i] = c; });
    var per = {};      /* sym -> { cycles: {idx: {days:[cycleDay], sevs:[..]}} } */
    var cyclesWithData = {};
    cmp.forEach(function (c) {
      /* v16: حد فیلتر lim — برای چرخه‌های غیر آخر همان e است (رفتار قبل حفظ شده) */
      all.filter(function (e) { return e.jdn >= c.s && e.jdn < c.lim; }).forEach(function (e) {
        cyclesWithData[c.i] = true;
        (e.r.symptoms || []).forEach(function (s) {
          per[s] = per[s] || {};
          per[s][c.i] = per[s][c.i] || { cd: [], sev: [] };
          per[s][c.i].cd.push(e.jdn - c.s + 1);
          var v = sevOf(e.r, s);
          if (v) per[s][c.i].sev.push(v);
        });
      });
    });
    var rows = Object.keys(per).map(function (s) {
      var idxs = Object.keys(per[s]).map(Number).sort(function (a, b) { return a - b; });
      return {
        k: s, cycleCount: idxs.length,
        cycles: idxs.map(function (i) {
          var d = per[s][i];
          var avgCd = Math.round(d.cd.reduce(function (a, b) { return a + b; }, 0) / d.cd.length);
          return { i: i, days: d.cd.length, avgCd: avgCd, sev: domSev(d.sev),
                   lab: byIdx[i] ? cycleLab(byIdx[i], false) : "" }; /* v17: برچسب تاریخ شروع */
        })
      };
    }).sort(function (a, b) { return b.cycleCount - a.cycleCount; });
    return {
      rows: rows, cyclesTotal: cb.cycles.length,
      cyclesWithData: Object.keys(cyclesWithData).length,
      cmpCount: cmp.length,   /* v17: تعداد چرخه‌هایی که واقعاً وارد مقایسه شده‌اند */
      comparable: rows.filter(function (r) { return r.cycleCount >= 2; })
    };
  }
