  function onChange(e) {
    var t = e.target;
    if (!t || !t.getAttribute) return;
    var which = t.getAttribute("data-sj-sel");
    if (!which) return;
    var cur = S.jal.d2j(S.formDate);
    if (which === "day") cur.jd = +t.value;
    if (which === "mon") cur.jm = +t.value;
    if (which === "year") cur.jy = +t.value;
    var ml = S.jal.monthLen(cur.jy, cur.jm);
    if (cur.jd > ml) cur.jd = ml;
    var jdn = S.jal.j2d(cur.jy, cur.jm, cur.jd);
    if (jdn > todayJdn()) { toast("تاریخ آینده قابل ثبت نیست"); renderPage(); return; }
    S.formDate = jdn;
    S.draft = draftFrom(keyOfJdn(jdn));
    S.delArmed = false;
    renderPage();
  }
  function onKey(e) {
    if (!S.opts.mount.contains(e.target)) return;
    var coverHit = e.target.closest ? e.target.closest("#sjCover") : null;
    if (coverHit && (e.key === "Enter" || e.key === " " || e.key === "Spacebar")) {
      openJournal(S.page); e.preventDefault(); return;
    }
    var tag = (e.target.tagName || "").toLowerCase();
    if (tag === "textarea" || tag === "input" || tag === "select") return;
    if (e.key === "Escape" && S.coverOpen) { closeJournal(); e.preventDefault(); return; }
    if (e.key === "ArrowLeft") { flipTo(S.page + 1, 1); e.preventDefault(); }
    else if (e.key === "ArrowRight") { flipTo(S.page - 1, -1); e.preventDefault(); }
    else if (e.key === "Home") { flipTo(0, -1); e.preventDefault(); }
    else if (e.key === "End") { flipTo(PAGES.length - 1, 1); e.preventDefault(); }
  }

