    OWN_FIELDS.forEach(function (f) {
      var v = d[f];
      if (f === "symptoms" || f === "mood") {
        if (v && v.length) next[f] = v.slice(); else delete next[f];
      } else if (f === "sev") {
        var clean = {};
        Object.keys(v || {}).forEach(function (k) {
          if ((d.symptoms || []).indexOf(k) > -1 && v[k]) clean[k] = v[k];
        });
        if (Object.keys(clean).length) next.sev = clean; else delete next.sev;
      } else if (v) next[f] = v;
      else delete next[f];
    });
    if (d.pain) next.pain = d.pain; else delete next.pain;
    /* اگر نه فیلد دفترچه ماند و نه فیلد تقویم، رکورد حذف می‌شود */
    if (!hasJournal(next) && !next.start) {
      S.adapter.deleteDay(key);
      return null;
    }
    S.adapter.saveDay(key, next);
    return key;
