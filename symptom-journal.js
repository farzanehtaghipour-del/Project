  /* دادهٔ مرور: چرخه‌هایی که شروعشان در ۳۶۵ روز گذشته است (+ چرخهٔ جاری همیشه)
     و دست‌کم یک علامت ثبت‌شده دارند. فیلتر ثبت هر چرخه همان فیلتر همه‌جای ماژول:
     e.jdn >= c.s && e.jdn < c.lim — هیچ منطق محاسبهٔ چرخهٔ جدیدی اضافه نشده. */
  function yearReviewData() {
    var cb = cycleBounds(), t = todayJdn(), from = t - YEAR_DAYS;
    var all = entries();
    var rows = [], inYear = 0;
    cb.cycles.forEach(function (c) {
      var inWin = c.current || (c.s >= from && c.s <= t);
      if (!inWin) return;
      inYear += 1;
      var bag = {};
      all.filter(function (e) { return e.jdn >= c.s && e.jdn < c.lim; }).forEach(function (e) {
        (e.r.symptoms || []).forEach(function (s) {
          bag[s] = bag[s] || { days: 0, sev: [] };
          bag[s].days += 1;
          var v = sevOf(e.r, s);
          if (v) bag[s].sev.push(v);
        });
      });
      var ks = Object.keys(bag);
      if (!ks.length) return;   /* فقط چرخه‌های دارای حداقل یک علامت ثبت‌شده */
      /* ترتیب علائم: بیشترین روزِ ثبت ← شدت بیشتر ← ترتیب الفبایی */
      ks.sort(function (a, b) {
        return (bag[b].days - bag[a].days) ||
          ((SEV_RANK[domSev(bag[b].sev)] || 0) - (SEV_RANK[domSev(bag[a].sev)] || 0)) ||
          (a < b ? -1 : a > b ? 1 : 0);
      });
      rows.push({
        c: c, lab: cycleLab(c, true),   /* همیشه با سال — مثل «۲۶ شهریور ۱۴۰۵» */
        syms: ks.map(function (k) { return { k: k, days: bag[k].days, sev: domSev(bag[k].sev) }; })
      });
    });
    rows.sort(function (a, b) { return b.c.s - a.c.s; });   /* جدیدترین بالا */
    return { rows: rows, inYear: inYear };
  }
