  function domSev(sevs) {
    var best = "", bn = 0;
    (sevs || []).forEach(function (v) {
      var c = sevs.filter(function (x) { return x === v; }).length;
      if (c > bn || (c === bn && SEV_RANK[v] > SEV_RANK[best])) { best = v; bn = c; }
    });
    return best;
  }
